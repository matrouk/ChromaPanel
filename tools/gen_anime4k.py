"""Translate an Anime4K mpv GLSL shader into HLSL for ChromaPanel.

    python tools/gen_anime4k.py third_party/anime4k/Anime4K_Restore_CNN_M.glsl src/Anime4K.cs

Anime4K ships as mpv "hook" shaders: a chain of passes, each reading named
textures and saving one. This keeps the structure exactly and changes only
the syntax:

    X_texOff(vec2(a, b))      ->  Ld(Tn, p + int2(a, b), hi)
    X_tex(X_pos)              ->  Ld(Tn, p, hi)
    mat4(v...) * expr         ->  mul(expr, float4x4(v...))     (same maths:
                                  GLSL fills mat4 by column, HLSL by row, and
                                  mul(row-vector, M) undoes the difference)
    return result + MAIN      ->  MAIN + result * Residual       (strength)

tests/GpuTests.cs re-implements the network on the CPU straight from the
original GLSL - not from this output - and compares, so a translation slip
here shows up as a failing test rather than a subtly wrong picture.
"""
import io
import re
import sys

src_path, out_path = sys.argv[1], sys.argv[2]
src = io.open(src_path, encoding="utf-8").read()

licence = []
for line in src.splitlines():
    if not line.startswith("//"):
        break
    licence.append(line)
assert any("MIT License" in l for l in licence), "expected bloc97's MIT header"

passes = re.split(r"(?m)^//!DESC", src)[1:]
hlsl = []
entries, inputs, outputs = [], [], []

for i, p in enumerate(passes):
    name = "A4K_P%d" % (i + 1)
    binds = re.findall(r"//!BIND (\w+)", p)
    save = re.findall(r"//!SAVE (\w+)", p)[0]
    # MAIN (the desktop) is always t0; intermediates are t1.. in bind order.
    order = [b for b in binds if b != "MAIN"]
    reg = {"MAIN": "T0"}
    for k, b in enumerate(order):
        reg[b] = "T%d" % (k + 1)
    entries.append(name)
    inputs.append(order)
    outputs.append(save)

    body = p[p.index("vec4 hook()"):]
    body = body[body.index("{") + 1: body.rindex("}")]
    macros = re.findall(r"(?m)^#define (\w+)(\([^)]*\))? (.*)$", p)

    out = ["// ---- pass %d: %s -> %s" % (i + 1, "+".join(binds), save)]
    defined = []
    for mname, margs, mbody in macros:
        def tex_off(m):
            return "Ld(%s, p + int2(%s), hi)" % (reg[m.group(1)], m.group(2))
        mbody = re.sub(r"(\w+)_texOff\(vec2\(([^)]*)\)\)", tex_off, mbody)
        mbody = re.sub(r"(\w+)_tex\(\1_pos\)", lambda m: "Ld(%s, p, hi)" % reg[m.group(1)], mbody)
        assert "_tex" not in mbody and "vec" not in mbody, "untranslated macro: " + mbody
        out.append("#define %s%s %s" % (mname, margs or "", mbody))
        defined.append(mname)

    if i == 0:
        # MAIN's alpha must not matter: we feed the desktop, whose alpha is arbitrary.
        for vals in re.findall(r"mat4\(([^)]*)\)", body):
            assert max(abs(float(v)) for v in vals.split(",")[12:16]) == 0.0, "pass 1 reads alpha"

    def mat(m):
        return "mul(%s, float4x4(%s))" % (m.group(2), m.group(1))
    body = re.sub(r"mat4\(([^)]*)\)\s*\*\s*(go_\d+\([^)]*\)|g_\d+)", mat, body)
    body = body.replace("vec4 result", "float4 result").replace("vec4(", "float4(")
    final = "return result + MAIN_tex(MAIN_pos);"
    if final in body:
        body = body.replace(final, "return float4(saturate(Ld(T0, p, hi).rgb + result.rgb * Residual), 1.0);")
    assert "mat4" not in body and "vec" not in body and "_tex" not in body, "untranslated body in pass %d" % (i + 1)

    out.append("float4 %s(float4 pos : SV_Position) : SV_Target" % name)
    out.append("{")
    out.append("    int2 p = int2(pos.xy);")
    out.append("    uint w, h; T0.GetDimensions(w, h);")
    out.append("    int2 hi = int2(w, h) - 1;")
    for line in body.strip("\n").splitlines():
        out.append("    " + line.strip())
    out.append("}")
    for mname in defined:
        out.append("#undef " + mname)
    hlsl.append("\n".join(out))

assert outputs[-1] == "MAIN", "last pass should write the picture"

ntex = max(len(x) for x in inputs)
header = [
    "Texture2D<float4> T0 : register(t0);   // the desktop (MAIN)",
] + ["Texture2D<float4> T%d : register(t%d);" % (k, k) for k in range(1, ntex + 1)] + [
    "",
    "cbuffer Params : register(b0) { float Strength; uint Mode; float2 Unused; };",
    "// 50% strength is the network as trained; 100% doubles its correction.",
    "static const float Residual = Strength * 2.0;",
    "",
    "float4 Ld(Texture2D<float4> t, int2 p, int2 hi) { return t.Load(int3(clamp(p, int2(0, 0), hi), 0)); }",
    "",
]

cs = []
cs.append("// <auto-generated>")
cs.append("//   From %s by tools/gen_anime4k.py. Do not edit by hand." % src_path.replace("\\", "/"))
cs.append("// </auto-generated>")
cs.append("//")
cs.extend(licence)
cs.append("")
cs.append("namespace ChromaPanel")
cs.append("{")
cs.append("    /// <summary>Anime4K Restore CNN (M): an 8-pass network that rebuilds line art at native resolution.</summary>")
cs.append("    internal static class Anime4K")
cs.append("    {")
cs.append("        public const string Hlsl = @\"")
cs.append("\n".join(header + hlsl).replace('"', '""'))
cs.append("\";")
cs.append("")
cs.append("        /// <summary>Pixel shader entry point for each pass, in order.</summary>")
cs.append("        public static readonly string[] Entries = { %s };" % ", ".join('"%s"' % e for e in entries))
cs.append("")
cs.append("        /// <summary>Intermediate textures each pass reads, bound to t1, t2... (t0 is always the desktop).</summary>")
cs.append("        public static readonly string[][] Inputs =")
cs.append("        {")
for x in inputs:
    cs.append("            new string[] { %s }," % ", ".join('"%s"' % n for n in x))
cs.append("        };")
cs.append("")
cs.append("        /// <summary>Texture each pass writes; \"MAIN\" means the final picture.</summary>")
cs.append("        public static readonly string[] Outputs = { %s };" % ", ".join('"%s"' % o for o in outputs))
cs.append("    }")
cs.append("}")
io.open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(cs) + "\n")
print("%d passes -> %s (%d textures max per pass)" % (len(passes), out_path, ntex + 1))
